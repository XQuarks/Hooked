/** 一张地图的深度上限 */
const depthOf = (m) => mapMaxDepth(m);

/** 实际刷鱼数 = max(1, round(count × FISH_DENSITY))（与 game.js::spawnFish 一致） */
const realCount = (z) => Math.max(1, Math.round(z.count * FISH_DENSITY));

const fmt = (n) => String(n).replace(/\B(?=(\d{3})+(?!\d))/g, ',');
const cost = (key, lv) => upgradeCost(key, lv);
const sumCost = (key, upTo) => {
  let s = 0;
  for (let i = 0; i < upTo; i++) s += cost(key, i);
  return s;
};

/** 四段块（项目的文档规范：概述 / 状态 / 读者 / 关联） */
const header = (title, { summary, status, reader, related }) =>
  `# ${title}

${STAMP}

> **概述**：${summary}
>
> **状态**：${status}
>
> **读者**：${reader}
>
> **关联**：${related}

---
`;

/** markdown 表格：rows[0] 作表头 */
function table(rows) {
  const [head, ...body] = rows;
  const line = (cells) => `| ${cells.join(' | ')} |`;
  const sep = `|${head.map(() => '---').join('|')}|`;
  return [line(head), sep, ...body.map(line)].join('\n');
}

/** 取 8 条鱼做起飞曲线抽样：按身价升序等距，且必定含最小与最大 */
function flightSamples(n = 8) {
  const sorted = [...SPECIES].sort((a, b) => a.value - b.value);
  const out = [];
  for (let i = 0; i < n; i++) {
    const idx = Math.round((i * (sorted.length - 1)) / (n - 1));
    const s = sorted[idx];
    if (!out.includes(s)) out.push(s);
  }
  return out;
}

