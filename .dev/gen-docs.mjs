/**
 * 这个脚本存在的意义是「文档 = 从代码生成」，但**生成模板自己**可以写死数字 ——
 * 而写死的数字**永远是幂等的**，于是 `gen-docs check` 永远绿。
 *
 * 真实事故：`doc05` 的模板里写死过「全部 6 通」，而紧接着的表格是 `CALLS.map()` 生成的
 * —— 于是 `docs/05` 上半页说「全部 6 通」，往下 100 行却列出 `### 1` ~ `### 9`。
 * `check` 报的是「重新生成的文本与磁盘上的一致」，**它验的是幂等性，不是正确性**。
 * 这是整个防漂移体系里最要命的一种漏法（比 `lint-docs` 能抓的任何一种都隐蔽），
 * 所以在这里补一条自检，把这类字面量变成**会挂的断言**。
 *
 * 规则：模板里出现「数字 + 量词」就报警 —— 这种数字必须写成 `${X.length}` 插值。
 * 确有正当理由的（比如"第 3 层海域"这类不随数据变的序数），在该行加 `@hardcode-ok` 并写明理由。
 */
const HARDCODE_UNITS = ['通', '张地图', '种鱼', '种地图', '把枪', '项升级', '个 App', '个 GLYPH', '张海图', '条鱼'];

function assertNoHardcodedCounts() {
  const self = fs.readFileSync(fileURLToPath(import.meta.url), 'utf8');
  const rawLines = self.split('\n');
  // ① 去掉 `${...}` 插值 —— 它们的**求值结果**才是"活的"数字，源码里不该有别的数字
  // ② 去掉注释，但**必须保住换行**，否则报出来的行号会整体错位
  //    （同一个坑 `lint-structure.mjs` 踩过：sanitize 吃掉换行 → 行号错位 → 整关空过）
  const stripped = self
    .replace(/\$\{[^{}]*\}/g, ' ')
    .replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, ''))
    .replace(/\/\/[^\n]*/g, '');

  const bad = [];
  stripped.split('\n').forEach((line, i) => {
    // `@hardcode-ok` 写在注释里，所以要看**原文**那一行
    if (/@hardcode-ok/.test(rawLines[i] || '')) return;
    for (const u of HARDCODE_UNITS) {
      const m = line.match(new RegExp('\\d+\\s*' + u));
      if (m) bad.push(`L${i + 1}  「${m[0]}」  ${(rawLines[i] || '').trim().slice(0, 70)}`);
    }
  });
  return bad;
}

const hardcoded = assertNoHardcodedCounts();
if (hardcoded.length) {
  console.error('\n✗ 生成模板里写死了派生数字 —— 它们永远不会过期，`check` 也就永远绿：\n');
  for (const b of hardcoded) console.error(`    ${b}`);
  console.error('\n改成插值（例如 CALLS.length 那一处写成 ${CALLS.length} 通）；');
  console.error('确有正当理由的，在该行加 @hardcode-ok 并写明原因。\n');
  process.exit(1);
}

