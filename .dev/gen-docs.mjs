/**
 * gen-docs.mjs — 从 `src/config.js` 生成 `docs/` 下的数值参考文档
 *
 * 为什么要有这个脚本：
 *   项目里所有数值的唯一来源是 `src/config.js`，但 README / DESIGN 里长期
 *   手工抄了一份副本，于是反复出现「文档写着 9 条鱼、代码其实是 18 条」
 *   这类漂移（历史上一共抓到 4 批）。
 *   这里不再手抄：**文档 = 从代码生成**，改了 config.js 重跑一次即可。
 *
 * 用法：
 *   node .dev/gen-docs.mjs            # 生成/覆盖 docs/01~05
 *   node .dev/gen-docs.mjs check      # 只校验（不写盘），有差异则退出码 1
 *
 * 产出：
 *   docs/01-世界与地图.md
 *   docs/02-鱼类图鉴.md
 *   docs/03-升级与成本.md
 *   docs/04-物理与经济.md
 *   docs/05-剧情与世界观.md
 *   （docs/README.md 是手写索引，本脚本不碰）
 *
 * ⚠ 本脚本只写上面这 5 个文件，不碰 README / DESIGN / STRUCTURE。
 */
