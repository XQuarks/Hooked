/** markdown 表格：rows[0] 作表头 */
function table(rows) {
  const [head, ...body] = rows;
  const line = (cells) => `| ${cells.join(' | ')} |`;
  const sep = `|${head.map(() => '---').join('|')}|`;
  return [line(head), sep, ...body.map(line)].join('\n');
}

/**
 * 逐帧复刻 `guns.js::_updateGun` + `_shoot`，算出某把枪在 `seconds` 秒内的
 * **总伤害上限**（A4 用：余量 = 上限 ÷ 鱼的血量，> 1 才打得下来）。
 *
 * 为什么要在生成器里跑一遍模拟，而不是手抄一张表：
 *   "深层血牛的余量极薄"这句话在 GAMEPLAY §6.4 里挂了两轮，但那个数字
 *   只存在于一段一次性脚本里 —— 改了 `dmg` / `cd` / `airTimeout` 之后没人会重算。
 *   现在它跟着 `config.js` 自动重生成。
 *
 * 口径（**是上限，不是实战值**）：
 *   ① 全程按住；单点枪 = 以冷却允许的最快速率连点（它的理论上限）；
 *   ② 每一发都命中**同一条鱼**，散弹的 6 颗弹丸全中；
 *   ③ 不计滞空位移、换目标、击退、`airTimeout` 之外的任何中断。
 *
 * ⚠ 分派条件必须和 `guns.js::_shoot()` 的 `switch (g.mech)` **一模一样** ——
 *   两边的分支规则一旦不同，这张表就会印出一个游戏里不存在的伤害。
 */
const GUN_DT = 1 / 60;
function gunOutputCeiling(id, lv, seconds) {
  const g = gunById(id);
  const s = gunStats(id, lv);
  // ⚠ 这就是 guns.js 的分派条件：能长按的机制（auto/burst/laser）走每帧驱动，
  //   其余（single/pierce）只认"按下那一发"。
  const holdable = g.mech === 'auto' || g.mech === 'burst' || g.mech === 'laser';
  // ⚠⚠ **必须与 `guns.js::_shoot()` 的判据逐字同源** —— 走 `fireBranchOf()`（下方定义，
  //   是那边规则的唯一镜像）。散弹枪的 mech 是 single，所以不能拿 mech 当分派条件，
  //   这正是 B11 那个死代码 bug 的成因。改一边就要改另一边。
  const branch = fireBranchOf(g);

  let cd = 0, reloadT = 0, heat = 0, spin = 0, ammo = s.mag || 0;
  let total = 0, shots = 0;

  const fire = () => {
    let d = s.damage;
    if (branch === 'laser') d *= 1 + Math.min(s.rampMax, s.ramp * heat);
    let c = s.cooldown;
    if (branch === 'auto' && s.spinup > 0) c *= 1 + (1 - Math.min(1, spin / s.spinup));
    cd = c;
    if (branch === 'burst') ammo = Math.max(0, ammo - 1);
    total += d * (branch === 'shotgun' ? s.pellets : 1);
    shots++;
  };

  for (let i = 0, steps = Math.floor(seconds / GUN_DT); i <= steps; i++) {
    if (cd > 0) cd = Math.max(0, cd - GUN_DT);
    if (reloadT > 0) {
      reloadT -= GUN_DT;
      if (reloadT <= 0) { reloadT = 0; if (s.mag) ammo = s.mag; heat = 0; }
      continue;
    }
    if (!holdable) { if (cd <= 0) fire(); continue; }
    if (branch === 'auto') spin = Math.min(s.spinup, spin + GUN_DT);
    if (branch === 'laser') {
      heat += GUN_DT;
      if (s.mag && heat >= s.mag) { reloadT = s.reload; cd = 0; continue; }
    }
    if (cd > 0) continue;
    if (branch === 'burst' && s.mag && ammo <= 0) { reloadT = s.reload; cd = 0; continue; }
    fire();
  }
  return { total, shots };
}

/**
 * **`guns.js::_shoot()` 分派规则的唯一镜像**：先看 `pellets > 1`，再看 `mech`。
 * `gunOutputCeiling()` 与下面的"死弹丸"检查都走它 —— 三处必须同源。
 *
 * 历史（B11）：v0.7 第四批之前游戏那边是纯 `switch (g.mech)` + `case 'shotgun'`，
 * 而**没有任何一把枪的 `mech` 叫 `shotgun`** → 声明了 `pellets` 的枪也进不去那个分支，
 * 散弹枪的 6 弹丸从来没生效过。
 */
const fireBranchOf = (g) => ((g.pellets || 0) > 1 ? 'shotgun' : g.mech);

/**
 * 声明了多颗弹丸、却走不到弹丸分支的枪 —— 现在应当**恒为空**。
 * 留着的意义是**绊线**：谁要是把分派规则改回"只看 `mech`"，这里会立刻报警，
 * 而不是像 B11 那样静默错两年。
 */
const deadPelletGuns = GUNS.filter((g) => (g.pellets || 0) > 1 && fireBranchOf(g) !== 'shotgun');

/** 取 8 条鱼做起飞曲线抽样：按身价升序等距，且必定含最小与最大 */
function flightSamples(n = 8) {
  const sorted = [...SPECIES].sort((a, b) => a.value - b.value);
  const out = [];
  for (let i = 0; i < n; i++) {
    const idx = Math.round((i * (sorted.length - 1)) / (n - 1));
    const s = sorted[idx];
    if (!out.includes(s)) out.push(s);
  }
  return out;
}

