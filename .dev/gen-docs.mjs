let changed = 0;
for (const [name, text] of FILES) {
  const p = path.join(OUT_DIR, name);
  const next = text.replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';
  const prev = fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : null;
  if (prev === next) {
    console.log(`  =  ${name}  （无变化）`);
    continue;
  }
  changed++;
  if (CHECK_ONLY) {
    console.log(`  !  ${name}  ${prev === null ? '（缺失）' : '（与代码不一致）'}`);
  } else {
    fs.writeFileSync(p, next);
    console.log(`  ✓  ${name}  ${prev === null ? '新建' : '已更新'}  ${(next.length / 1024).toFixed(1)} KB`);
  }
}

