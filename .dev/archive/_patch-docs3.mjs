// ── 两阶段：先把**全部**替换在内存里试一遍，全都对得上才批量写盘 ──
const fail = [];
const staged = [];
for (const [file, list] of Object.entries(jobs)) {
  let src = fs.readFileSync(file, 'utf8');
  let n = 0;
  for (const [a, b, label] of list) {
    const hits = src.split(a).length - 1;
    if (hits !== 1) { fail.push(`${label}（${file}）：锚点命中 ${hits} 次，应为 1`); continue; }
    src = src.replace(a, b);
    n++;
  }
  staged.push([file, src, n, list.length]);
}

if (fail.length) {
  console.error('\n✗✗ 有锚点对不上，**任何文件都没有写盘**：\n  ' + fail.join('\n  '));
  process.exit(1);
}

for (const [file, src, n, total] of staged) {
  fs.writeFileSync(file, src);
  console.log(`✓ ${file}：${n}/${total} 处`);
}
console.log('\n✓ 四份文档全部写盘完成');
