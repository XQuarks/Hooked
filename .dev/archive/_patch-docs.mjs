import fs from 'node:fs';

const log = [];
const patch = (file, pairs) => {
  let t = fs.readFileSync(file, 'utf8');
  for (const [from, to, label] of pairs) {
    if (!t.includes(from)) { log.push(`✗ ${file}｜${label}`); continue; }
    t = t.replace(from, to);
    log.push(`✓ ${file}｜${label}`);
  }
  fs.writeFileSync(file, t);
};

