function spliceBlock(text, startAnchor, endAnchor, newBody, label) {
  const lines = text.split('\n');
  const a = lines.findIndex((l) => l.startsWith(startAnchor));
  const b = lines.findIndex((l) => l.startsWith(endAnchor));
  if (a < 0 || b < 0 || b < a) { fail.push(`${label}: 锚点定位失败 (a=${a} b=${b})`); return text; }
  const body = newBody.replace(/\n+$/, '').split('\n');
  const out = [...lines.slice(0, a), ...body, ...lines.slice(b)];
  console.log(`✓ ${label}：替换第 ${a + 1}~${b} 行（${b - a} 行 → ${body.length} 行）`);
  return out.join('\n');
}

