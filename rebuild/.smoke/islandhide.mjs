import puppeteer from 'file:///C:/Users/guoxiaoyan/.workbuddy/binaries/node/workspace/node_modules/puppeteer-core/lib/esm/puppeteer/puppeteer-core.js';
import path from 'node:path';
const CHROME='C:/Program Files/Google/Chrome/Application/chrome.exe';
const HTML=path.resolve('dist/index.html');
const KEY='absurd-fishing-3d-save-v2';
const sleep=(ms)=>new Promise(r=>setTimeout(r,ms));
const browser=await puppeteer.launch({executablePath:CHROME,headless:'new',args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage();
await page.setViewport({width:430,height:900,deviceScaleFactor:1});
await page.goto('file:///'+HTML.replace(/\\/g,'/')+'#debug',{waitUntil:'load'});
await page.evaluate(()=>localStorage.clear());
await page.reload({waitUntil:'load'});
await sleep(1100);
await page.evaluate((k)=>{const s=JSON.parse(localStorage.getItem(k));s.trips=1;s.fired=['intro'];s.queue=[];localStorage.setItem(k,JSON.stringify(s));},KEY);
await page.reload({waitUntil:'load'});
await sleep(1000);
await page.evaluate(()=>{const b=[...document.querySelectorAll('button')].find(x=>(x.textContent||'').includes('开始')||(x.textContent||'').includes('继续'));b?.click();});
await sleep(1200);
const shore=await page.evaluate(()=>({island:document.querySelector('.island')?.className??null, dim:!!document.querySelector('.hud-top.dim'), overlay:document.querySelector('.comic,.call,.notice')?.className??null, phase:window.__af?.debugState?.().phase, queue:JSON.parse(localStorage.getItem('absurd-fishing-3d-save-v2')||'{}').queue?.map(q=>q.kind)}));
console.log('岸边:', JSON.stringify(shore));
await page.mouse.click(215,540);
await sleep(2200);
const fishing=await page.evaluate(()=>({phase:window.__af?.debugState?.().phase, island:document.querySelector('.island')?.className??null, dim:!!document.querySelector('.hud-top.dim')}));
console.log('下潜中:', JSON.stringify(fishing));
await browser.close();
